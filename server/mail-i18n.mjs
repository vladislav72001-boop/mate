/**
 * Transactional email i18n (ru / en / hu / uk).
 * Locale comes from order.payload.locale (saved at checkout).
 */

export const MAIL_LOCALES = ['ru', 'en', 'hu', 'uk'];

const INTERRUPT = {
  ru: 'ru-RU',
  en: 'en-GB',
  hu: 'hu-HU',
  uk: 'uk-UA',
};

export function normalizeMailLocale(raw) {
  const v = String(raw || '').toLowerCase().trim().slice(0, 2);
  if (v === 'ua') return 'uk';
  if (MAIL_LOCALES.includes(v)) return v;
  return 'ru';
}

export function localeFromOrder(order) {
  const p = order?.payload || {};
  return normalizeMailLocale(p.locale || p.lang || p.language || order?.locale);
}

/** Locale from UI request: body / X-Mate-Locale / Accept-Language (default en). */
export function localeFromRequest(req, fallback = 'en') {
  const body = req?.body || {};
  const headers = req?.headers || {};
  const headerLocale = headers['x-mate-locale'] || headers['x-locale'] || headers['x-language'];
  const accept = String(headers['accept-language'] || '').split(',')[0] || '';
  return normalizeMailLocale(
    body.locale || body.lang || body.language || headerLocale || accept || fallback,
  );
}

export function intlLocale(locale) {
  return INTERRUPT[normalizeMailLocale(locale)] || 'ru-RU';
}

function interpolate(template, vars = {}) {
  return String(template ?? '').replace(/\{\{(\w+)\}\}/g, (_, key) => (
    vars[key] != null ? String(vars[key]) : ''
  ));
}

