export function mailT(locale, key, vars = {}) {
  const loc = normalizeMailLocale(locale);
  const dict = DICT[loc] || DICT.ru;
  const template = dict[key] ?? DICT.ru[key] ?? key;
  return interpolate(template, vars);
}

export function statusLabel(locale, status) {
  return mailT(locale, status) || status;
}
